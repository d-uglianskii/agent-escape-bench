def _page(title: str, body: str) -> str:
    links = "".join(f'<a href="{html.escape(u)}">{html.escape(t)}</a>' for t, u in CTA_LINKS)
    return (f"<!doctype html><html lang=en><head><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>"
            f"<title>{html.escape(title)}</title><style>{_CSS}</style></head><body><main>{body}"
            f"<div class=cta><p>{html.escape(CTA)}</p>{links}</div>"
            f"<footer class=muted>Generated by <a href='{REPO_URL}'>agent-escape-bench</a> {__version__}.</footer></main></body></html>")


