STATUS_LABEL = {"enforced": "has a check", "partial": "weak check", "text-only": "text only",
                "judgment": "needs human judgment", "unclassified": "not classified"}


def scan_text(rep: ScanReport) -> str:
    counted = rep.counted()
    c = Counter(r.status for r in rep.rules)
    lines = [f"agent-escape-bench scan {__version__}", f"repo: {rep.repo}",
             f"instruction files: {', '.join(rep.instruction_files) or 'none'}", "",
             f"  RULES WITH A MECHANICAL CHECK  {round(rep.share() * 100)}% of {len(counted)} checkable rules",
             f"  has a check {c['enforced']} · weak check {c['partial']} · text only {c['text-only']} · "
             f"judgment {c['judgment']} · unclassified {c['unclassified']}", ""]
    for r in rep.rules:
        if r.status in ("text-only", "partial", "enforced"):
            lines.append(f"  [{STATUS_LABEL[r.status]:<15}] {r.text[:90]}")
            lines.append(f"  {'':<17} {r.file}:{r.line}" + (f"  <- {r.evidence[0]}" if r.evidence else ""))
    if rep.findings:
        lines += ["", "  Findings:", *[f"  - {f}" for f in rep.findings]]
    lines += ["", "Heuristic scan: it shows where to look, it does not prove enforcement.",
              "Want the gaps closed? EGD assessment: d.uglianskii@gmail.com"]
    return "\n".join(lines)


def scan_markdown(rep: ScanReport) -> str:
    c = Counter(r.status for r in rep.rules)
    out = ["# Agent rules enforcement scan", "", f"- Repository: `{rep.repo}`",
           f"- Instruction files: {', '.join(f'`{f}`' for f in rep.instruction_files) or 'none'}", "",
           f"**{round(rep.share() * 100)}%** of {len(rep.counted())} checkable rules have a mechanical check "
           f"(has a check {c['enforced']}, weak check {c['partial']}, text only {c['text-only']}).", "",
           "A check existing is not the same as a check working: measure shell guards with `aeb bench`.", "",
           "| Rule | Topic | Status | Evidence |", "| --- | --- | --- | --- |"]
    for r in rep.rules:
        topic = TOPICS.get(r.topic, {}).get("label", "") if r.topic else ""
        out.append(f"| {r.text.replace('|', '/')[:120]} <br>`{r.file}:{r.line}` | {topic} | {STATUS_LABEL[r.status]} | "
                   f"{'; '.join(r.evidence[:3]) or '-'} |")
    if rep.findings:
        out += ["", "## Findings", "", *[f"- {f}" for f in rep.findings]]
    out += ["", "---", "", CTA, "", " · ".join(f"[{t}]({u})" for t, u in CTA_LINKS), "",
            "Heuristic scan: it shows where to look, it does not prove enforcement."]
    return "\n".join(out)


def scan_html(rep: ScanReport) -> str:
    e = html.escape
    c = Counter(r.status for r in rep.rules)
    cls = {"enforced": "okk", "partial": "part", "text-only": "esc", "judgment": "", "unclassified": ""}
    rows = "".join(
        f"<tr><td>{e(r.text)}<br><span class=muted><code>{e(r.file)}:{r.line}</code></span></td>"
        f"<td>{e(TOPICS.get(r.topic, {}).get('label', '') if r.topic else '')}</td>"
        f"<td><span class='tag {cls[r.status]}'>{STATUS_LABEL[r.status]}</span></td>"
        f"<td>{'<br>'.join(e(x) for x in r.evidence[:3]) or '-'}</td></tr>" for r in rep.rules)
    findings = "".join(f"<li>{e(f)}</li>" for f in rep.findings)
    share = round(rep.share() * 100)
    body = (f"<h1>Agent rules enforcement scan</h1><p class=muted>{e(rep.repo)}</p>"
            f"<div class=kpis><div class='kpi {'ok' if share >= 70 else 'bad'}'><b>{share}%</b>of checkable rules have a mechanical check</div>"
            f"<div class=kpi><b>{c['text-only']}</b>rules rest on text alone</div>"
            f"<div class=kpi><b>{c['enforced']}</b>rules have a check. Measure it with aeb bench</div></div>"
            + (f"<h2>Findings</h2><ul>{findings}</ul>" if findings else "")
            + f"<h2>Rules</h2><table><tr><th>Rule</th><th>Topic</th><th>Status</th><th>Evidence</th></tr>{rows}</table>"
            + "<p class=muted>Heuristic scan: it shows where to look, it does not prove enforcement.</p>")
    return _page("Agent rules enforcement scan", body)
